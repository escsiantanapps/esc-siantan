async function capture(name, contentSelector = '.sched-matrix-table') {
  await page.locator(contentSelector).first().waitFor({ state: 'visible' })
  const dismiss = page.locator('.animate-toast-in [aria-label="Tutup"]')
  while (await dismiss.count()) await dismiss.first().click()
  await page.evaluate(() => window.scrollTo(0, 0))
  // Snapshot menunggu transisi warna selesai agar dark mode tidak tertangkap setengah berubah.
  await page.evaluate(() => Promise.all(document.getAnimations()
    .filter(animation => Number.isFinite(animation.effect?.getComputedTiming().endTime))
    .map(animation => animation.finished.catch(() => {}))))
  for (let attempt = 0; attempt < 3; attempt += 1) {
    await page.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))))
    const bitmap = await page.screenshot({ path: `${output}/${name}.png`, fullPage: true })
    const statistics = await sharp(bitmap).stats()
    if (statistics.channels.slice(0, 3).some(channel => channel.stdev > 5)) return
  }
  assert.fail(`Screenshot ${name} tidak boleh kosong.`)
}

